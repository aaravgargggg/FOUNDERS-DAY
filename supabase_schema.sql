-- ============================================================================
-- Supabase Schema & Policies for Jaipuria Founders' Day Feedback System
-- Run this in your Supabase SQL Editor (Dashboard -> SQL Editor)
-- ============================================================================

-- 1. Ensure `events` table has sample events populated
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name TEXT NOT NULL
);

-- Enable RLS on events
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;

-- Allow public read access to events for the dropdown
CREATE POLICY "Allow public read access to events"
    ON public.events
    FOR SELECT
    TO anon, authenticated
    USING (true);

-- Insert Founders' Day events into `events` table
INSERT INTO public.events (event_name)
VALUES
    ('Opening Ceremony'),
    ('Cultural Programme'),
    ('Student Exhibition'),
    ('Sports Events'),
    ('Prize Distribution'),
    ('Founders’ Day Celebration');


-- 2. Ensure `feedback` table allows public INSERT
-- If feedback table is already created with columns:
-- (id, parent_name, ward_name, ward_class, email_id, event_name, rating, feedback)

-- Enable RLS on feedback
ALTER TABLE public.feedback ENABLE ROW LEVEL SECURITY;

-- CRUCIAL POLICY: This allows parents (public/anon users) to submit feedback!
-- Without this policy, Supabase throws error 42501 (violates row-level security).
DROP POLICY IF EXISTS "Allow public insert to feedback" ON public.feedback;

CREATE POLICY "Allow public insert to feedback"
    ON public.feedback
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

-- Optional: Allow admin/authenticated users to view feedback
DROP POLICY IF EXISTS "Allow authenticated read to feedback" ON public.feedback;

CREATE POLICY "Allow authenticated read to feedback"
    ON public.feedback
    FOR SELECT
    TO authenticated
    USING (true);
